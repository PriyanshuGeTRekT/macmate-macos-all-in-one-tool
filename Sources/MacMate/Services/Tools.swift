// MARK: - Clipboard history

struct ClipItem: Identifiable, Equatable {
    let id = UUID()
    let text: String
    let date: Date
    var pinned = false
    let source: String?
}

/// Remembers the last 100 things you copied (text only, in memory only, password managers excluded).
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()

    @Published private(set) var items: [ClipItem] = []
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    private let limit = 100
    private static let secretTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                      "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in self?.poll() }
        timer?.tolerance = 0.2
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard UserDefaults.standard.bool(forKey: Keys.clipEnabled) else { return }
        let types = pb.types?.map(\.rawValue) ?? []
        guard !types.contains(where: ClipboardHistory.secretTypes.contains) else { return }
        guard let text = pb.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.utf8.count < 200_000 else { return }
        record(text, source: NSWorkspace.shared.frontmostApplication?.localizedName)
    }

    func record(_ text: String, source: String?) {
        var pinned = false
        if let i = items.firstIndex(where: { $0.text == text }) {
            pinned = items[i].pinned
            items.remove(at: i)
        }
        items.insert(ClipItem(text: text, date: Date(), pinned: pinned, source: source), at: 0)
        if items.count > limit, let drop = items.lastIndex(where: { !$0.pinned }) { items.remove(at: drop) }
    }

    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(item.text, forType: .string)
        lastChange = pb.changeCount
        record(item.text, source: item.source)
    }

    func togglePin(_ item: ClipItem) {
        if let i = items.firstIndex(of: item) { items[i].pinned.toggle() }
    }

    func delete(_ item: ClipItem) { items.removeAll { $0.id == item.id } }
    func clear() { items.removeAll { !$0.pinned } }
}

// MARK: - Microphone mute

final class MicMute: ObservableObject {
    static let shared = MicMute()

    @Published private(set) var muted = false
    @Published private(set) var deviceName = ""
    private var savedVolume: Float32?

    private static func defaultInput() -> AudioDeviceID? {
        var id = AudioDeviceID(0)
        var size = UInt32(MemoryLayout<AudioDeviceID>.size)
        var addr = AudioObjectPropertyAddress(mSelector: kAudioHardwarePropertyDefaultInputDevice,
                                              mScope: kAudioObjectPropertyScopeGlobal, mElement: kAudioObjectPropertyElementMain)
        guard AudioObjectGetPropertyData(AudioObjectID(kAudioObjectSystemObject), &addr, 0, nil, &size, &id) == noErr, id != 0 else { return nil }
        return id
    }

    func refresh() {
        guard let dev = MicMute.defaultInput() else { muted = false; deviceName = "No microphone"; return }
        var addr = AudioObjectPropertyAddress(mSelector: kAudioDevicePropertyMute, mScope: kAudioDevicePropertyScopeInput,
                                              mElement: kAudioObjectPropertyElementMain)
        var value: UInt32 = 0
        var size = UInt32(MemoryLayout<UInt32>.size)
        if AudioObjectGetPropertyData(dev, &addr, 0, nil, &size, &value) == noErr { muted = value != 0 }

        var nameAddr = AudioObjectPropertyAddress(mSelector: kAudioObjectPropertyName, mScope: kAudioObjectPropertyScopeGlobal,
                                                  mElement: kAudioObjectPropertyElementMain)
        var name: Unmanaged<CFString>?
        var nameSize = UInt32(MemoryLayout<Unmanaged<CFString>?>.size)
        if AudioObjectGetPropertyData(dev, &nameAddr, 0, nil, &nameSize, &name) == noErr, let name {
            deviceName = name.takeRetainedValue() as String
        }
    }

    @discardableResult
    func setMuted(_ mute: Bool) -> Bool {
        guard let dev = MicMute.defaultInput() else { return false }
        var addr = AudioObjectPropertyAddress(mSelector: kAudioDevicePropertyMute, mScope: kAudioDevicePropertyScopeInput,
                                              mElement: kAudioObjectPropertyElementMain)
        var value: UInt32 = mute ? 1 : 0
        var ok = false
        if AudioObjectHasProperty(dev, &addr) {
            ok = AudioObjectSetPropertyData(dev, &addr, 0, nil, UInt32(MemoryLayout<UInt32>.size), &value) == noErr
        }
        if !ok {
            // Devices without a mute switch: drop the input gain to zero instead.
            var volAddr = AudioObjectPropertyAddress(mSelector: kAudioDevicePropertyVolumeScalar, mScope: kAudioDevicePropertyScopeInput,
                                                     mElement: kAudioObjectPropertyElementMain)
            var current: Float32 = 0
            var size = UInt32(MemoryLayout<Float32>.size)
            if AudioObjectGetPropertyData(dev, &volAddr, 0, nil, &size, &current) == noErr {
                if mute { savedVolume = current }
                var target: Float32 = mute ? 0 : (savedVolume ?? 0.7)
                ok = AudioObjectSetPropertyData(dev, &volAddr, 0, nil, size, &target) == noErr
                if ok { muted = mute; return true }
            }
        }
        refresh()
        return ok
    }

    func toggle() {
        refresh()
        let target = !muted
        if setMuted(target) {
            HUD.shared.show(target ? "Microphone muted" : "Microphone on", symbol: target ? "mic.slash.fill" : "mic.fill")
        } else {
            HUD.shared.show("This microphone cannot be muted", symbol: "exclamationmark.triangle")
        }
    }
}

// MARK: - Screen text capture (OCR)

enum ScreenOCR {
    static func recognize(_ image: CGImage) -> String {
        let request = VNRecognizeTextRequest()
        request.recognitionLevel = .accurate
        request.usesLanguageCorrection = true
        try? VNImageRequestHandler(cgImage: image, options: [:]).perform([request])
        return (request.results ?? []).compactMap { $0.topCandidates(1).first?.string }.joined(separator: "\n")
    }

    /// Lets the user drag a rectangle, reads the text in it and puts it on the clipboard.
    static func capture() {
        let path = NSTemporaryDirectory() + "macmate-ocr-\(UUID().uuidString).png"
        inBackground {
            shell("/usr/sbin/screencapture", ["-i", "-x", path])
            defer { try? FileManager.default.removeItem(atPath: path) }
            guard let image = NSImage(contentsOfFile: path)?.cgImage(forProposedRect: nil, context: nil, hints: nil) else { return }
            let text = recognize(image)
            DispatchQueue.main.async {
                guard !text.isEmpty else { HUD.shared.show("No text found in that area", symbol: "text.viewfinder"); return }
                let pb = NSPasteboard.general
                pb.clearContents()
                pb.setString(text, forType: .string)
                HUD.shared.show("Copied \(text.count) characters of text", symbol: "text.viewfinder")
            }
        }
    }
}

// MARK: - Display dimmer

struct DisplayEntry: Identifiable, Equatable {
    let id: CGDirectDisplayID
    let name: String
    let builtIn: Bool
}

/// Software dimming through the display's gamma table. Works on any monitor, including ones
/// whose brightness macOS cannot control, and can go darker than the hardware minimum.
final class DisplayDimmer: ObservableObject {
    static let shared = DisplayDimmer()

    @Published private(set) var displays: [DisplayEntry] = []
    @Published private(set) var levels: [CGDirectDisplayID: Double] = [:]
    private var timer: Timer?

    func refreshDisplays() {
        displays = NSScreen.screens.compactMap { screen in
            guard let n = screen.deviceDescription[NSDeviceDescriptionKey("NSScreenNumber")] as? NSNumber else { return nil }
            let id = CGDirectDisplayID(n.uint32Value)
            return DisplayEntry(id: id, name: screen.localizedName, builtIn: CGDisplayIsBuiltin(id) != 0)
        }
    }

    func level(for id: CGDirectDisplayID) -> Double { levels[id] ?? 1 }

    func set(_ level: Double, for id: CGDirectDisplayID) {
        let l = max(0.15, min(1, level))
        if l >= 0.995 { levels[id] = nil } else { levels[id] = l }
        apply()
        if levels.isEmpty {
            timer?.invalidate()
            timer = nil
        } else if timer == nil {
            // macOS resets gamma after sleep, display changes and colour-profile switches.
            timer = Timer.scheduledTimer(withTimeInterval: 4, repeats: true) { [weak self] _ in self?.apply(restoreFirst: false) }
        }
    }

    func reset() {
        levels.removeAll()
        timer?.invalidate()
        timer = nil
        CGDisplayRestoreColorSyncSettings()
    }

    private func apply(restoreFirst: Bool = true) {
        if restoreFirst { CGDisplayRestoreColorSyncSettings() }
        for (id, level) in levels {
            let m = CGGammaValue(level)
            CGSetDisplayTransferByFormula(id, 0, m, 1, 0, m, 1, 0, m, 1)
        }
    }
}

// MARK: - System toggles and one-shot tools

enum SystemToggles {
    static var hiddenFilesShown: Bool {
        UserDefaults(suiteName: "com.apple.finder")?.bool(forKey: "AppleShowAllFiles") ?? false
    }

    static func setHiddenFilesShown(_ on: Bool) {
        shell("/usr/bin/defaults", ["write", "com.apple.finder", "AppleShowAllFiles", "-bool", on ? "true" : "false"])
        shell("/usr/bin/killall", ["Finder"])
    }

    static var desktopIconsHidden: Bool {
        guard let v = UserDefaults(suiteName: "com.apple.finder")?.object(forKey: "CreateDesktop") as? Bool else { return false }
        return !v
    }

    static func setDesktopIconsHidden(_ hidden: Bool) {
        shell("/usr/bin/defaults", ["write", "com.apple.finder", "CreateDesktop", "-bool", hidden ? "false" : "true"])
        shell("/usr/bin/killall", ["Finder"])
    }

    static var darkMode: Bool { UserDefaults.standard.string(forKey: "AppleInterfaceStyle") == "Dark" }

    static func setDarkMode(_ on: Bool) -> Bool {
        appleScript("tell application \"System Events\" to tell appearance preferences to set dark mode to \(on)").ok
    }

    static func sleepDisplay() { shell("/usr/bin/pmset", ["displaysleepnow"]) }
    static func restartFinder() { shell("/usr/bin/killall", ["Finder"]) }
    static func restartDock() { shell("/usr/bin/killall", ["Dock"]) }

    /// Ejects every external or removable volume. Returns the names it ejected.
    static func ejectAll() -> [String] {
        let keys: [URLResourceKey] = [.volumeIsEjectableKey, .volumeIsRemovableKey, .volumeIsInternalKey, .volumeNameKey]
        var ejected: [String] = []
        for url in FileManager.default.mountedVolumeURLs(includingResourceValuesForKeys: keys, options: [.skipHiddenVolumes]) ?? [] {
            guard let v = try? url.resourceValues(forKeys: Set(keys)) else { continue }
            let external = v.volumeIsEjectable == true || v.volumeIsRemovable == true || v.volumeIsInternal == false
            guard external, url.path != "/" else { continue }
            if (try? NSWorkspace.shared.unmountAndEjectDevice(at: url)) != nil { ejected.append(v.volumeName ?? url.lastPathComponent) }
        }
        return ejected
    }

    static func pickColor() {
        NSColorSampler().show { color in
            guard let c = color?.usingColorSpace(.sRGB) else { return }
            let hex = String(format: "#%02X%02X%02X", Int((c.redComponent * 255).rounded()),
                             Int((c.greenComponent * 255).rounded()), Int((c.blueComponent * 255).rounded()))
            let pb = NSPasteboard.general
            pb.clearContents()
            pb.setString(hex, forType: .string)
            HUD.shared.show("Copied \(hex)", symbol: "eyedropper")
        }
    }
}

enum LoginItem {
    static var available: Bool { Bundle.main.bundlePath.hasSuffix(".app") }
    static var enabled: Bool { available && SMAppService.mainApp.status == .enabled }

    @discardableResult
    static func set(_ on: Bool) -> Bool {
        guard available else { return false }
        do {
            if on { try SMAppService.mainApp.register() } else { try SMAppService.mainApp.unregister() }
            return true
        } catch {
            return false
        }
    }
}
